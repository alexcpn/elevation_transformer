from . import itm_wrapper as itm
import logging as log


class ITMLossWinnf:
    def getItmLoss(self, freq_mhz, height_cbsd_agl, height_rx_agl, elevation_data, distance_m):
        """
         Give height above Ground level
        # R2-AIP-27 ITM Parameters:
        """
        confidence = 0.05
        reliability = 0.2

        refractivity = 314.0  # Typical
        refractivity_final = False
        dielectric = 25  # WINNF
        conductivity = 0.02  # WINNF
        climate = 5  # Continental temperate
        polarization = 0  # WINNF
        mdvar = 13  # WINNF

        num_of_profile = len(elevation_data)
        distance_between_points = distance_m / num_of_profile-1
        elevation_data = [num_of_profile-1, distance_between_points] + elevation_data
        # Sanity checks on input parameters
        if freq_mhz < 40.0 or freq_mhz > 10000:
            raise Exception("Frequency outside range [40MHz - 10GHz]")

        loss, ver0, ver1, err, mode = itm.point_to_point(
            elevation_data,
            height_cbsd_agl,
            height_rx_agl,
            dielectric,
            conductivity,
            refractivity,
            freq_mhz,
            climate,
            polarization,
            confidence,
            reliability,
            mdvar,
            refractivity_final,
        )

        # log.debug(f"Loss={loss} For reliability={reliability} and confidence={confidence} stepsize= {distance_between_points}")
        return loss

    def getItmLossClassic(self, frequency, height1, height2, elevation_data, distance_m):
        # https://github.com/Wireless-Innovation-Forum/Spectrum-Access-System/blob/master/src/harness/reference_models/propagation/itm/itm_test.py#L206
        confidence_vals = [0.5, 0.9, 0.1]
        reliability_vals = [0.01, 0.1, 0.5, 0.9, 0.99]
        expected_losses = [
            128.6,
            137.6,
            119.6,
            132.2,
            140.8,
            123.5,
            135.8,
            144.3,
            127.2,
            138.0,
            146.5,
            129.4,
            139.7,
            148.4,
            131.0,
        ]

        refractivity = 314.0  # Typical
        refractivity_final = True
        dielectric = 15  # Typical for ground
        conductivity = 0.005  # Typical for ground
        climate = 5  # Continental temperate
        polarization = 0  # Vertical
        mdvar = 12
        k = 0

        num_of_profile = len(elevation_data) - 1
        elevation_data.insert(0, num_of_profile)
        elevation_data.insert(1, distance_m / num_of_profile)

        loss, ver0, ver1, err, mode = itm.point_to_point(
            elevation_data,
            height1,
            height2,
            dielectric,
            conductivity,
            refractivity,
            frequency,
            climate,
            polarization,
            confidence_vals[k],
            reliability_vals[k],
            mdvar,
            refractivity_final,
        )

        log.debug(
            f"Loss={loss} For reliability={reliability_vals[0]} and confidence={confidence_vals[0]} Excpected={expected_losses[k]} "
        )
        return loss


